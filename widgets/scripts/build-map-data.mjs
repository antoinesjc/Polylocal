// Generates src/map-data.js: the projected map (land, region overlays,
// hub positions, arcs, Europe zoom) used by the <polylocal-map> widget.
// Run with: npm run data
import fs from 'node:fs';
import { createRequire } from 'node:module';
import * as topo from 'topojson-client';
import * as simp from 'topojson-simplify';
import { geoNaturalEarth1, geoPath, geoGraticule10, geoDistance } from 'd3-geo';

const require = createRequire(import.meta.url);
let world = require('world-atlas/countries-50m.json');
world = simp.presimplify(world);
world = simp.simplify(world, 0.02);
const countries = topo.feature(world, world.objects.countries).features;

// ---- projection -----------------------------------------------------------
const W = 1200;
// Frame: Iberia to Japan's longitude, North Cape (71°N) down to Singapore.
const frame = { type: 'MultiPoint', coordinates: [[-10, 36], [-10, 71], [26, 71.5], [40, 68], [135, 54], [135, 20], [104, -1.5], [-9, 35]] };
const PAD_X = 36;
const PAD_Y = 30;
const proj = geoNaturalEarth1().rotate([-62, 0]).fitWidth(W - 2 * PAD_X, frame);
const path = geoPath(proj);
let b = path.bounds(frame);
proj.translate([proj.translate()[0] - b[0][0] + PAD_X, proj.translate()[1] - b[0][1] + PAD_Y]);
b = path.bounds(frame);
const H = Math.ceil(b[1][1]) + PAD_Y;

// ---- regions (ISO 3166-1 numeric) -----------------------------------------
const EU27 = ['040', '056', '100', '191', '196', '203', '208', '233', '246', '250', '276', '300', '348', '372', '380', '428', '440', '442', '470', '528', '616', '620', '642', '703', '705', '724', '752'];
const REGIONS = {
  asiaCore: ['158'],                 // Taiwan
  asia: ['156', '702'],              // Mainland China, Singapore
  ceeCore: ['616'],                  // Poland
  cee: ['203', '703', '348', '642', '440', '428', '233'], // CZ SK HU RO LT LV EE
  eu: EU27,
};

const id = (s) => String(s).padStart(3, '0');
const round = (d, p = 1) => d.replace(/-?\d+\.\d+/g, (m) => String(+(+m).toFixed(p)));
// The Americas sit on the map's back seam at this rotation; leave them out.
const SKIP = ['840', '124', '484'];
const inView = (f) => {
  if (SKIP.includes(id(f.id))) return false;
  const bb = path.bounds(f);
  return !(bb[1][0] < -20 || bb[0][0] > W + 20 || bb[1][1] < -20 || bb[0][1] > H + 20);
};
const joined = (codes) => countries.filter((f) => codes.includes(id(f.id))).map((f) => path(f)).filter(Boolean).map((d) => round(d, 0)).join('');

const land = countries.filter(inView).map((f) => path(f)).filter(Boolean).map((d) => round(d, 0)).join('');
const graticule = round(path(geoGraticule10()), 0);
const regions = Object.fromEntries(Object.entries(REGIONS).map(([k, codes]) => [k, joined(codes)]));

// ---- hubs, arcs, zoom -----------------------------------------------------
const CITIES = {
  taipei: [121.56, 25.03],
  singapore: [103.82, 1.35],
  warsaw: [21.01, 52.23],
  brussels: [4.35, 50.85],
};
const px = {};
const pct = {};
for (const [k, ll] of Object.entries(CITIES)) {
  const [x, y] = proj(ll);
  px[k] = [+x.toFixed(1), +y.toFixed(1)];
  pct[k] = [+(x / W * 100).toFixed(2), +(y / H * 100).toFixed(2)];
}
const arc = (a, c, lift) => {
  const [x1, y1] = px[a];
  const [x2, y2] = px[c];
  const len = Math.hypot(x2 - x1, y2 - y1);
  return `M${x1},${y1} Q${((x1 + x2) / 2).toFixed(1)},${((y1 + y2) / 2 - len * lift).toFixed(1)} ${x2},${y2}`;
};
const arcs = {
  taipeiWarsaw: arc('taipei', 'warsaw', 0.28),
  taipeiBrussels: arc('taipei', 'brussels', 0.36),
  warsawBrussels: arc('warsaw', 'brussels', 0.18),
};

// Europe zoom: scale and transform-origin (in %) that fit Europe into the frame.
// The whole EU, Lapland to Cyprus, centred in the frame with a small margin.
const eb = path.bounds({ type: 'MultiPoint', coordinates: [[-11, 35], [-11, 71], [33, 71], [35, 35], [-6, 34.5]] });
const x0 = eb[0][0] / W * 100;
const x1 = eb[1][0] / W * 100;
const y0 = eb[0][1] / H * 100;
const y1 = eb[1][1] / H * 100;
const S = +(0.94 * Math.min(100 / (x1 - x0), 100 / (y1 - y0))).toFixed(2);
// Pick the origin so the box centre lands in the middle of the frame, kept inside the map.
const origin = (c) => {
  const o = (50 - c * S) / (1 - S);
  const v = (o / 100) * (1 - 1 / S);               // viewBox offset as a share of the map
  const clamped = Math.min(Math.max(v, 0), 1 - 1 / S);
  return +((clamped * 100) / (1 - 1 / S)).toFixed(2);
};
const zoom = { scale: S, originX: origin((x0 + x1) / 2), originY: origin((y0 + y1) / 2) };

const km = (a, c) => Math.round(geoDistance(CITIES[a], CITIES[c]) * 6371 / 100) * 100;
const distances = { taipeiWarsaw: km('taipei', 'warsaw'), taipeiBrussels: km('taipei', 'brussels') };

const data = { width: W, height: H, graticule, land, regions, cities: pct, arcs, zoom, distances };
const out = `// Generated by scripts/build-map-data.mjs. Do not edit by hand.\n// Natural Earth 1:50m via world-atlas (public domain).\nexport default ${JSON.stringify(data)};\n`;
fs.writeFileSync(new URL('../src/map/map-data.js', import.meta.url), out);
console.log(`map-data.js: ${(out.length / 1024).toFixed(0)} KB, ${W}x${H}`, { cities: pct, zoom, distances });
